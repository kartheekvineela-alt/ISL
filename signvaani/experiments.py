"""Day 4 experiments: model comparison (blueprint Table R2) and ablation (Table R4).

    python -m signvaani.experiments compare --data data/keypoints --out docs/results/model_comparison.md
    python -m signvaani.experiments ablate --model gru --data data/keypoints --out docs/results/ablation.md

compare trains BiGRU, Transformer and 1D-CNN on the same data with the same seed and settings: a random
split (signer-dependent) and leave-one-signer-out (signer-independent), and times one sign on the CPU.
ablate retrains one model with: hands only, hands + pose, hands + pose + face (the full model), the full
model without augmentation, and the full model without velocity features.

On converted INCLUDE folders, whose "signers" are the official split names, the official split takes the
place of leave-one-signer-out. Every training also saves its run record in runs/, so signvaani.confusion
works on any of them. These are many trainings (compare: 3 x (signers + 1), ablate: 5 x signers), so start
them in the evening, or pass --epochs 40 for a quicker first look. Other train options (--patience,
--batch-size, --no-balance, --no-trim, ...) are passed through.
"""
import argparse
import time
from pathlib import Path

import numpy as np
import torch

from . import train as T
from .data import index_clips, signers
from .export_onnx import cpu_ms
from .landmarks import ALL_GROUPS, FEATURE_DIM
from .models import MODELS, build_model

NAMES = {"gru": "BiGRU + attention", "transformer": "Transformer", "cnn": "1D-CNN"}
ABLATIONS = [  # (row of Table R4, landmark groups, augmentation, velocity features, row it is compared with)
    ("Hands only", ["hands"], True, True, None),
    ("Hands + pose", ["hands", "pose"], True, True, 0),
    ("Hands + pose + face (full model)", list(ALL_GROUPS), True, True, 1),
    ("Full model without augmentation", list(ALL_GROUPS), False, True, 2),
    ("Full model without velocity features", list(ALL_GROUPS), True, False, 2),
]


def evaluate(clips, labels, args, tag=""):
    """Signer-independent result of one configuration: LOSO, or INCLUDE's official split."""
    if set(signers(clips)) <= T.OFFICIAL_SPLIT:
        folds = T.one_split(clips, labels, args, ["test"], ["val"])
        mode = "signer"
    else:
        folds = T.loso(clips, labels, args)
        mode = "loso"
    T.save_run(mode, folds, labels, args, tag)
    top1 = np.array([f["top1"] for f in folds])
    return {"mean": float(top1.mean()), "std": float(top1.std()), "folds": len(folds),
            "macro_f1": float(np.mean([f["macro_f1"] for f in folds]))}


def sign_ms(model_name, n_labels, seq_len):
    """CPU milliseconds to classify one sign window (batch of 1, PyTorch); the weights do not matter."""
    model = build_model(model_name, FEATURE_DIM, n_labels).eval()
    with torch.no_grad():
        return cpu_ms(model, torch.zeros(1, seq_len, FEATURE_DIM))


def protocol(clips):
    return ("INCLUDE official split" if set(signers(clips)) <= T.OFFICIAL_SPLIT
            else f"leave-one-signer-out, {len(signers(clips))} folds")


def header(title, data, clips, labels, args):
    return [f"# {title}", "",
            f"Data `{Path(data).as_posix()}`: {len(clips)} clips, {len(labels)} classes; signer-independent "
            f"protocol: {protocol(clips)}. Seed {args.seed}, up to {args.epochs} epochs, "
            f"class balance {'on' if args.balance else 'off'}, live-window trim {'on' if args.trim else 'off'}. "
            f"Generated by `python -m signvaani.experiments` on {time.strftime('%Y-%m-%d')}.", ""]


def compare(opts, rest):
    clips = index_clips(opts.data)
    labels = sorted({c.sign for c in clips})
    rows = []
    for name in opts.models:
        args = T.make_parser().parse_args(["--data", opts.data, "--model", name, *rest])
        print(f"\n########## {NAMES[name]}: random split ##########")
        random_fold = T.one_split(clips, labels, args, random=True)
        T.save_run("random", random_fold, labels, args)
        print(f"\n########## {NAMES[name]}: signer-independent ##########")
        result = evaluate(clips, labels, args)
        params = sum(p.numel() for p in build_model(name, FEATURE_DIM, len(labels)).parameters())
        rows.append((NAMES[name], random_fold[0]["top1"], result, params, sign_ms(name, len(labels), args.seq_len)))

    lines = header("Table R2: model comparison", opts.data, clips, labels, args) + [
        "| Model | Random split top-1 | Signer-independent top-1 (mean ± std) | Macro-F1 | Parameters | CPU ms / sign |",
        "|---|---|---|---|---|---|"]
    for name, random_top1, r, params, ms in rows:
        lines.append(f"| {name} | {random_top1:.1%} | {r['mean']:.1%} ± {r['std']:.1%} | {r['macro_f1']:.3f} | "
                     f"{params:,} | {ms:.1f} |")
    best = max(rows, key=lambda row: row[2]["mean"])
    lines += ["", f"Best signer-independent model: **{best[0]}**. Use it for the ablation "
              f"(`python -m signvaani.experiments ablate --model ...`). CPU ms / sign is PyTorch on this computer, "
              "batch of 1; `signvaani.export_onnx` prints the ONNX time."]
    return lines


def ablate(opts, rest):
    clips = index_clips(opts.data)
    labels = sorted({c.sign for c in clips})
    results = []
    for title, parts, augment, velocity, _ in ABLATIONS:
        extra = ["--parts", *parts] + ([] if augment else ["--no-augment"]) + ([] if velocity else ["--no-velocity"])
        args = T.make_parser().parse_args(["--data", opts.data, "--model", opts.model, *extra, *rest])
        print(f"\n########## {title} ##########")
        tag = "_" + "-".join(parts) + ("" if augment else "_noaug") + ("" if velocity else "_novel")
        results.append(evaluate(clips, labels, args, tag))

    lines = header(f"Table R4: ablation ({NAMES[opts.model]})", opts.data, clips, labels, args) + [
        "| Configuration | Top-1 (mean ± std) | Macro-F1 | Change |", "|---|---|---|---|"]
    for (title, *_, ref), r in zip(ABLATIONS, results):
        change = "-" if ref is None else f"{100 * (r['mean'] - results[ref]['mean']):+.1f} points vs \"{ABLATIONS[ref][0]}\""
        lines.append(f"| {title} | {r['mean']:.1%} ± {r['std']:.1%} | {r['macro_f1']:.3f} | {change} |")
    lines += ["", "Each change compares a row with the row named in it: adding pose to hands, adding face to "
              "hands + pose, and taking augmentation or velocity features away from the full model."]
    return lines


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("compare", help="Table R2: BiGRU vs Transformer vs 1D-CNN")
    c.add_argument("--models", nargs="+", choices=list(MODELS), default=list(MODELS))
    a = sub.add_parser("ablate", help="Table R4: landmark groups, augmentation, velocity features")
    a.add_argument("--model", choices=list(MODELS), default="gru", help="the best model from compare")
    for q in (c, a):
        q.add_argument("--data", default="data/keypoints")
        q.add_argument("--out", help="also write the Markdown table here, e.g. docs/results/ablation.md")
    opts, rest = p.parse_known_args(argv)
    if any(r in rest for r in ("--loso", "--random-split", "--final", "--test-signers", "--model", "--parts")):
        p.error("the split and the model are chosen by signvaani.experiments itself")

    lines = (compare if opts.cmd == "compare" else ablate)(opts, rest)
    text = "\n".join(lines) + "\n"
    print("\n" + text)
    if opts.out:
        Path(opts.out).parent.mkdir(parents=True, exist_ok=True)
        Path(opts.out).write_text(text, encoding="utf-8")
        print(f"saved {opts.out}")


if __name__ == "__main__":
    main()
