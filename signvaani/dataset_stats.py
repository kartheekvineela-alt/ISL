"""Dataset statistics for the report (Day 2, blueprint Table R1).

    python -m signvaani.dataset_stats                                       # data/keypoints, every signer
    python -m signvaani.dataset_stats --out docs/results/dataset_stats.md   # the table to commit
    python -m signvaani.dataset_stats --data data/include_keypoints/include50 --out docs/results/include50_stats.md

Counts the clips per sign and signer, the mean clip length and the share of frames with a hand, and
prints them as Markdown: Table R1 (summary), clips per sign and signer, and one row per signer. It reads
any folder laid out as <SIGN>/<signer>_<take>.npy, so converted INCLUDE clips work too; their "signer"
is the official split (train / val / test).
"""
import argparse
import datetime
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

import numpy as np

from .data import index_clips, vocabulary
from .landmarks import hands_share


@dataclass(frozen=True)
class ClipStat:
    sign: str
    signer: str
    frames: int
    hands: float  # share of frames with at least one hand


def clip_stats(root, signers=()):
    """One ClipStat per clip under root (only `signers` if given)."""
    out = []
    for c in index_clips(root):
        if signers and c.signer not in signers:
            continue
        clip = np.load(c.path)
        out.append(ClipStat(c.sign, c.signer, len(clip), hands_share(clip)))
    return out


def sign_order(signs):
    """Vocabulary order when every sign is in configs/vocabulary.json, otherwise alphabetical."""
    vocab = vocabulary()
    return [s for s in vocab if s in signs] if set(signs) <= set(vocab) else sorted(signs)


def summary(stats):
    """Table R1 values. Frames with hands is frame-weighted and leaves out IDLE, where resting hands
    are often out of view on purpose."""
    signs = sign_order({s.sign for s in stats})
    people = sorted({s.signer for s in stats})
    counts = defaultdict(int)
    for s in stats:
        counts[s.sign, s.signer] += 1
    takes = [counts[sign, p] for sign in signs for p in people]
    signing = [s for s in stats if s.sign != "IDLE"] or stats
    return {"signers": len(people), "classes": len(signs), "takes_min": min(takes), "takes_max": max(takes),
            "clips": len(stats), "mean_frames": float(np.mean([s.frames for s in stats])),
            "hands": sum(s.hands * s.frames for s in signing) / sum(s.frames for s in signing)}


def markdown(stats, root):
    signs = sign_order({s.sign for s in stats})
    people = sorted({s.signer for s in stats})
    r = summary(stats)
    takes = f"{r['takes_min']}" if r["takes_min"] == r["takes_max"] else f"{r['takes_min']}-{r['takes_max']}"
    lines = [
        "# Dataset statistics", "",
        f"Data: `{Path(root).as_posix()}`. Generated by `python -m signvaani.dataset_stats` on "
        f"{datetime.date.today().isoformat()}.", "",
        "## Table R1: Dataset summary", "",
        "| Signers | Classes | Takes / class / signer | Total clips | Mean clip length | Frames with hands |",
        "|---|---|---|---|---|---|",
        f"| {r['signers']} | {r['classes']} | {takes} | {r['clips']} | {r['mean_frames']:.0f} frames "
        f"| {r['hands']:.0%} |", "",
        "Frames with hands: share of all frames with at least one hand detected, over every sign except IDLE.",
        "", "## Clips per sign and signer", "",
        "| Sign | " + " | ".join(people) + " | Total | Mean frames | Hands |",
        "|---|" + "---|" * (len(people) + 3),
    ]
    by_sign = defaultdict(list)
    for s in stats:
        by_sign[s.sign].append(s)
    for sign in signs:
        rows = by_sign[sign]
        n = [sum(s.signer == p for s in rows) for p in people]
        lines.append(f"| {sign} | " + " | ".join(map(str, n)) + f" | {len(rows)} | "
                     f"{np.mean([s.frames for s in rows]):.0f} | {np.mean([s.hands for s in rows]):.0%} |")
    lines.append("| **Total** | " + " | ".join(str(sum(s.signer == p for s in stats)) for p in people)
                 + f" | {len(stats)} | | |")
    lines += ["", "Hands: mean over the sign's clips of the share of frames with a hand.", "",
              "## Per signer", "", "| Signer | Clips | Mean frames | Hands (signs, no IDLE) |", "|---|---|---|---|"]
    for p in people:
        rows = [s for s in stats if s.signer == p]
        signing = [s for s in rows if s.sign != "IDLE"] or rows
        lines.append(f"| {p} | {len(rows)} | {np.mean([s.frames for s in rows]):.0f} | "
                     f"{np.mean([s.hands for s in signing]):.0%} |")
    return "\n".join(lines) + "\n"


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--data", default="data/keypoints")
    p.add_argument("--signers", nargs="*", default=[], help="only these signers (default: all)")
    p.add_argument("--out", help="also write the Markdown here, e.g. docs/results/dataset_stats.md")
    args = p.parse_args(argv)

    stats = clip_stats(args.data, args.signers)
    if not stats:
        p.error(f"no clips for signers {args.signers} under {args.data}")
    text = markdown(stats, args.data)
    print(text, end="")
    if args.out:
        Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        Path(args.out).write_text(text, encoding="utf-8")
        print(f"saved {args.out}")


if __name__ == "__main__":
    main()
